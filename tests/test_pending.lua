test("pending edits never write CVars", function()
	local ns, env = newAddon()
	ns.Pending.set("groundEffectDensity", 128)
	ns.Pending.applyPreset("ultra")
	ns.Pending.applyPreset("default")
	eq(#env.cvars.writes, 0)
end)

test("pending values snap to step and clamp to range", function()
	local ns = newAddon()
	ns.Pending.set("groundEffectDensity", 1000)
	eq(ns.Pending.get("groundEffectDensity"), 256)
	ns.Pending.set("ResampleSharpness", 0.84)
	eq(ns.Pending.get("ResampleSharpness"), 0.8)
end)

test("a pending value equal to live is dropped", function()
	local ns = newAddon()
	ns.Pending.set("groundEffectDensity", 64)
	ns.Pending.set("groundEffectDensity", 40)
	eq(ns.Pending.count(), 0)
end)

test("presets fill pending values and are detected", function()
	local ns = newAddon()
	ns.Pending.applyPreset("balanced")
	eq(ns.Pending.get("groundEffectDensity"), 64)
	eq(ns.Pending.get("reflectionMode"), nil, "balanced leaves reflections unchanged")
	eq(ns.Pending.activePreset(), "balanced")
	ns.Pending.applyPreset("ultra")
	eq(ns.Pending.get("reflectionMode"), 3)
	eq(ns.Pending.activePreset(), "ultra")
end)

test("switching from ultra to balanced drops ultra-only values", function()
	local ns = newAddon()
	ns.Pending.applyPreset("ultra")
	ns.Pending.applyPreset("balanced")
	eq(ns.Pending.get("reflectionMode"), nil)
end)

test("default preset uses GetCVarDefault, not baked numbers", function()
	local ns, env = newAddon({ values = { groundEffectDensity = 200 } })
	env.cvars.store.groundEffectDensity.default = "48"
	ns.Pending.applyPreset("default")
	eq(ns.Pending.get("groundEffectDensity"), 48)
	eq(ns.Pending.activePreset(), "default")
end)

test("manual edit turns the preset into custom, and custom brings edits back", function()
	local ns = newAddon()
	ns.Pending.applyPreset("balanced")
	ns.Pending.set("groundEffectDensity", 96)
	eq(ns.Pending.activePreset(), "custom")
	ns.Pending.applyPreset("ultra")
	eq(ns.Pending.get("groundEffectDensity"), 128)
	truthy(ns.Pending.hasCustom())
	ns.Pending.applyPreset("custom")
	eq(ns.Pending.get("groundEffectDensity"), 96)
end)

test("unavailable settings are skipped by presets", function()
	local ns = newAddon({ missing = set({ "reflectionMode" }) })
	ns.Pending.applyPreset("ultra")
	eq(ns.Pending.get("reflectionMode"), nil)
	eq(ns.Pending.activePreset(), "ultra")
end)

test("validate rejects fade beyond draw distance", function()
	local ns = newAddon()
	ns.Pending.set("groundEffectFade", 300)
	local ok, errors = ns.Pending.validate(ns.Pending.changes())
	eq(ok, false)
	truthy(errors[1]:find("Grass fade start"), errors[1])
end)

test("validate checks horizonStart against live horizonClip", function()
	local ns = newAddon()
	ns.Pending.set("horizonStart", 5000)
	eq((ns.Pending.validate(ns.Pending.changes())), false)
	ns.Pending.set("horizonStart", 4000)
	eq((ns.Pending.validate(ns.Pending.changes())), true)
end)

test("validate rejects restricted settings", function()
	local ns, env = newAddon()
	ns.Pending.set("reflectionMode", 3)
	env.cvars.GetCVarInfo = function(name)
		local entry = env.cvars.store[name]
		return entry.value, entry.default, false, false, name == "reflectionMode", false, false
	end
	local ok, errors = ns.Pending.validate(ns.Pending.changes())
	eq(ok, false)
	truthy(errors[1]:find("restricted"), errors[1])
end)

test("changes are ordered tier 1 first", function()
	local ns = newAddon()
	ns.Pending.applyPreset("balanced")
	local changes = ns.Pending.changes()
	eq(ns.SettingsByKey[changes[1].cvar].tier, 1)
	eq(ns.SettingsByKey[changes[#changes].cvar].tier, 2)
end)
