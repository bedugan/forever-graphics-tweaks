local function keepTest(ns, cvar, value)
	ns.Pending.set(cvar, value)
	assert(ns.Preview.start())
	ns.Preview.keep()
end

test("restore original writes the baseline, not native defaults", function()
	local ns, env = newAddon({ values = { textureFilteringMode = 3 } })
	keepTest(ns, "textureFilteringMode", 5)
	keepTest(ns, "groundEffectDensity", 128)
	local ok = ns.Profiles.restoreOriginal()
	truthy(ok)
	eq(env.cvars.value("textureFilteringMode"), 3, "user's value, default is 2")
	eq(env.cvars.value("groundEffectDensity"), 40)
end)

test("baseline is captured once and not overwritten by later tests", function()
	local ns, env = newAddon()
	keepTest(ns, "textureFilteringMode", 5)
	keepTest(ns, "textureFilteringMode", 4)
	eq(env.db.baseline.values.textureFilteringMode, 2)
end)

test("restore original needs a baseline and refuses during a test", function()
	local ns = newAddon()
	eq((ns.Profiles.restoreOriginal()), false)
	ns.Pending.set("textureFilteringMode", 5)
	ns.Preview.start()
	eq((ns.Profiles.restoreOriginal()), false)
end)

test("reset baseline refuses during a test", function()
	local ns = newAddon()
	ns.Pending.set("textureFilteringMode", 5)
	ns.Preview.start()
	eq((ns.Profiles.resetBaseline()), false)
end)

test("profiles save effective values and load into pending only", function()
	local ns, env = newAddon()
	ns.Pending.applyPreset("ultra")
	truthy((ns.Profiles.save("  SteamOS Ultra  ")))
	contains(ns.Profiles.list(), "SteamOS Ultra")
	ns.Pending.clear()
	local writes = #env.cvars.writes
	truthy((ns.Profiles.load("SteamOS Ultra")))
	eq(#env.cvars.writes, writes, "loading writes nothing")
	eq(ns.Pending.get("reflectionMode"), 3)
	eq(ns.Pending.activePreset(), "ultra")
end)

test("profile names are validated", function()
	local ns = newAddon()
	eq((ns.Profiles.save("   ")), false)
	eq((ns.Profiles.save(string.rep("x", 41))), false)
end)

test("profile delete removes it", function()
	local ns = newAddon()
	ns.Profiles.save("Mac Balanced")
	ns.Profiles.delete("Mac Balanced")
	eq(#ns.Profiles.list(), 0)
end)

test("restore original puts back children that a restored parent rewrites", function()
	local ns, env = newAddon()
	keepTest(ns, "textureFilteringMode", 5)
	env.cvars.external("graphicsGroundClutter", 9)
	truthy((ns.Profiles.restoreOriginal()))
	eq(env.cvars.value("graphicsGroundClutter"), 5)
	eq(env.cvars.value("groundEffectDensity"), 40)
	eq(env.cvars.value("groundEffectDist"), 200)
end)
